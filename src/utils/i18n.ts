import type { RoleDefinition, UserRole } from "../types";

export type Language = "en" | "ms";

export const DEFAULT_LANGUAGE: Language = "en";
export const LANGUAGE_STORAGE_KEY = "pengekosan_language_preference";
export const LEGACY_LANGUAGE_STORAGE_KEY = "pengekosan_language";

export const getStoredLanguage = (): Language => {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  try {
    const saved =
      localStorage.getItem(LANGUAGE_STORAGE_KEY) ||
      localStorage.getItem(LEGACY_LANGUAGE_STORAGE_KEY);
    if (saved === "ms" || saved === "en") {
      return saved;
    }
  } catch (e) {
    console.error("Error reading language preference:", e);
  }
  return DEFAULT_LANGUAGE;
};

export const setStoredLanguage = (lang: Language): void => {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    localStorage.setItem(LEGACY_LANGUAGE_STORAGE_KEY, lang);
  } catch (e) {
    console.error("Error saving language preference:", e);
  }
  applyLanguageToDOM(lang);
};

export const applyLanguageToDOM = (lang: Language, activeSectionTitle?: string): void => {
  if (typeof document === "undefined") return;
  const normalized: Language = lang === "ms" ? "ms" : "en";
  document.documentElement.lang = normalized;
  const baseTitle =
    normalized === "en"
      ? "SmartCost — Costing & Managerial Accounting System"
      : "SmartCost — Sistem Pengekosan & Perakaunan Pengurusan";
  document.title = activeSectionTitle ? `${activeSectionTitle} · SmartCost` : baseTitle;
};

export const getLocale = (lang: Language): string => {
  return lang === "en" ? "en-US" : "ms-MY";
};

export const formatLocalizedNumber = (
  val: number,
  lang: Language,
  options?: Intl.NumberFormatOptions
): string => {
  const safeVal = Number.isFinite(val) ? val : 0;
  return safeVal.toLocaleString(getLocale(lang), options);
};

export const formatLocalizedDate = (
  input: Date | string | number,
  lang: Language,
  options?: Intl.DateTimeFormatOptions
): string => {
  const date = input instanceof Date ? input : new Date(input);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleDateString(getLocale(lang), options);
};

export const formatLocalizedTime = (
  input: Date | string | number,
  lang: Language,
  options?: Intl.DateTimeFormatOptions
): string => {
  const date = input instanceof Date ? input : new Date(input);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleTimeString(getLocale(lang), options);
};

export const formatLocalizedDateTime = (
  input: Date | string | number,
  lang: Language,
  options?: Intl.DateTimeFormatOptions
): string => {
  const date = input instanceof Date ? input : new Date(input);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleString(getLocale(lang), options);
};

export const formatUnitLabel = (unit: string | undefined | null, lang: Language): string => {
  const clean = (unit || "").trim();
  if (clean) return clean;
  return lang === "en" ? "units" : "unit";
};

