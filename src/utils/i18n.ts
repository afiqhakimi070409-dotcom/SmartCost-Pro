export type Language = "en" | "ms";

export const getStoredLanguage = (): Language => {
  try {
    const saved = localStorage.getItem("pengekosan_language_preference") || localStorage.getItem("pengekosan_language");
    if (saved === "ms" || saved === "en") {
      return saved;
    }
  } catch (e) {
    console.error("Error reading language preference:", e);
  }
  return "ms"; // Default is Bahasa Melayu for Malaysian SMEs
};

export const setStoredLanguage = (lang: Language): void => {
  try {
    localStorage.setItem("pengekosan_language_preference", lang);
    localStorage.setItem("pengekosan_language", lang);
  } catch (e) {
    console.error("Error saving language preference:", e);
  }
};

